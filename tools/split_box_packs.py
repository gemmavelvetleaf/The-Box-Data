#!/usr/bin/env python3
"""Generate small line-aligned transport chunks for The Box remote scene packs.

Human-maintained files live in /packs/*.txt and are never modified.
Generated output lives in /chunks and can be regenerated at any time.
"""
from __future__ import annotations

import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKS = ROOT / "packs"
OUT = ROOT / "chunks"
MAX_CHUNK_BYTES = 3000


def die(msg: str) -> None:
    raise SystemExit(f"ERROR: {msg}")


def parse_header(path: Path, text: str) -> tuple[str, str]:
    if text.startswith("\ufeff"):
        die(f"{path}: remove UTF-8 BOM; VERSION= must be the first bytes in the file")

    lines = text.splitlines()
    if not lines:
        die(f"{path}: empty file")

    first = lines[0].strip()
    if not first.upper().startswith("VERSION="):
        die(f"{path}: first line must be VERSION=")
    version = first[8:].strip()
    if not version:
        die(f"{path}: VERSION= cannot be blank")

    pack = ""
    for raw in lines[1:]:
        line = raw.strip()
        if not line or line.startswith("#") or line.startswith("//"):
            continue
        if line.startswith("["):
            break
        if line.upper().startswith("PACK="):
            pack = line[5:].strip()
            break

    if not pack:
        die(f"{path}: PACK= is required before the first scene")
    if pack != path.stem:
        die(f"{path}: PACK={pack} must match filename {path.stem}.txt")
    if "|" in path.stem:
        die(f"{path}: '|' is not allowed in a pack filename")

    return version, pack


def split_line_aligned(text: str, path: Path) -> list[str]:
    # Normalize repository transport to LF while preserving every logical line.
    normalized = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = normalized.splitlines(keepends=True)
    if normalized and not lines:
        lines = [normalized]

    chunks: list[str] = []
    current: list[str] = []
    current_bytes = 0

    for line in lines:
        n = len(line.encode("utf-8"))
        if n > MAX_CHUNK_BYTES:
            die(f"{path}: one line is {n} bytes; maximum is {MAX_CHUNK_BYTES}")
        if current and current_bytes + n > MAX_CHUNK_BYTES:
            chunks.append("".join(current))
            current = []
            current_bytes = 0
        current.append(line)
        current_bytes += n

    # splitlines(keepends=True) keeps a final non-newline line. Preserve it.
    if current:
        chunks.append("".join(current))
    if not chunks:
        chunks = [""]

    return chunks


def main() -> None:
    if not PACKS.is_dir():
        die(f"missing {PACKS}")

    files = sorted(PACKS.glob("*.txt"), key=lambda p: p.name.casefold())
    if not files:
        die("no /packs/*.txt files found")

    temp = ROOT / ".chunks-new"
    if temp.exists():
        shutil.rmtree(temp)
    temp.mkdir(parents=True)

    index_lines = ["# AUTO-GENERATED by tools/split_box_packs.py - DO NOT EDIT\n"]

    for path in files:
        text = path.read_text(encoding="utf-8")
        version, pack = parse_header(path, text)
        chunks = split_line_aligned(text, path)

        dest = temp / pack
        dest.mkdir(parents=True)
        for i, chunk in enumerate(chunks):
            (dest / f"{i:03d}.txt").write_text(chunk, encoding="utf-8", newline="")

        index_lines.append(f"{pack}|{version}|{len(chunks)}\n")
        print(f"{pack}: VERSION={version}, {len(chunks)} chunk(s)")

    (temp / "index.txt").write_text("".join(index_lines), encoding="utf-8", newline="")

    if OUT.exists():
        shutil.rmtree(OUT)
    temp.rename(OUT)


if __name__ == "__main__":
    main()
